#!/bin/sh
# Writes book/src/reference/cli.md from the `ticoraw` CLI's own --help output, so the
# documentation website's CLI reference can never drift from the code.
#
#   scripts/docs/cli-help.sh           # rewrite book/src/reference/cli.md
#   scripts/docs/cli-help.sh --check   # what CI runs: exit 1 with a diff if it is stale
#
# The subcommands are read from `ticoraw --help` (its "Commands:" section), so a new
# command appears in the reference without editing this script. Each one is run as
# `cargo run -q -p ticoraw-cli -- <command> --help`.
set -eu

root=$(CDPATH='' cd -- "$(dirname -- "$0")/../.." && pwd)
out="$root/book/src/reference/cli.md"

check=0
case "${1:-}" in
"") ;;
--check) check=1 ;;
*)
  echo "usage: $0 [--check]" >&2
  exit 2
  ;;
esac

cd "$root"
cargo build -q -p ticoraw-cli

ticoraw() {
  cargo run -q -p ticoraw-cli -- "$@"
}

top=$(ticoraw --help)
# Lines of the form "  <name>   <summary>" between "Commands:" and the next blank line.
commands=$(printf '%s\n' "$top" | awk '
  /^Commands:/ { on = 1; next }
  on && /^[[:space:]]*$/ { exit }
  on { print $1 }
' | grep -v '^help$')

if [ -z "$commands" ]; then
  echo "cli-help.sh: found no commands in 'ticoraw --help'" >&2
  exit 1
fi

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

# The backticks below are Markdown code spans, not command substitutions.
# shellcheck disable=SC2016
{
  cat <<'EOF'
<!-- Generated by scripts/docs/cli-help.sh from `ticoraw <command> --help`. Do not edit:
     change the help text in crates/ticoraw-cli/src and run the script again. -->

# CLI reference

This page is the built-in help of the `ticoraw` command-line tool, copied word for word.
You can print the same text yourself with `ticoraw --help` and `ticoraw <command> --help`
(or `ticoraw help <command>`).

For worked examples, see [Converting photos](../converting.md). To install the tool, see
[Install ticoraw](../photographers/install.md).

Commands:

EOF
  for c in $commands; do
    printf -- '- [`ticoraw %s`](#ticoraw-%s)\n' "$c" "$c"
  done
  printf '\n## `ticoraw`\n\n```text\n%s\n```\n' "$top"
  for c in $commands; do
    printf '\n## `ticoraw %s`\n\n```text\n' "$c"
    ticoraw "$c" --help
    printf '```\n'
  done
} >"$tmp"

if [ "$check" = 1 ]; then
  if ! diff -u "$out" "$tmp"; then
    echo >&2
    echo "book/src/reference/cli.md is out of date with the CLI's --help output." >&2
    echo "Run scripts/docs/cli-help.sh and commit the result." >&2
    exit 1
  fi
  echo "cli-help.sh: book/src/reference/cli.md is up to date"
else
  mkdir -p "$(dirname -- "$out")"
  cp "$tmp" "$out"
  echo "cli-help.sh: wrote book/src/reference/cli.md"
fi
